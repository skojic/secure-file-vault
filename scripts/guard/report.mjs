#!/usr/bin/env node
// Generates .guard/handoff/<module>.md from git and the ledger only. A new session (or another
// agent) reads this instead of re-deriving state. Agent-written text appears only under
// "Agent notes (claims, not verified)".
// Usage: node scripts/guard/report.mjs [<module>] [--print]
import { pathToFileURL } from 'node:url';
import { HANDOFF_MAX_CHARS } from './config.mjs';
import { checkPlan } from './check-plan.mjs';
import { checkScope } from './check-scope.mjs';
import { checkScenarios } from './check-scenarios.mjs';
import {
  cli, repoRoot, activeModule, approval, readPlan, readStatus, readJsonl, treeHash, git,
  writeLedgerFile, planPath, GuardError,
} from './lib.mjs';

const cap = (items, n) => (items.length > n ? [...items.slice(0, n), `…and ${items.length - n} more`] : items);

function safe(fn, fallback) {
  try {
    return fn();
  } catch (err) {
    return fallback(err);
  }
}

// The first failing condition, in build-loop order, decides the next step.
function nextStep(module, ctx) {
  const plan = planPath(module);
  if (ctx.planErrors.length) return `The plan has ${ctx.planErrors.length} error(s); fix ${plan} (see node scripts/guard/check-plan.mjs ${plan}).`;
  if (ctx.appr.state === 'missing') return `The plan is not approved. A person approves it in a terminal: node scripts/guard/approve-plan.mjs ${plan}`;
  if (ctx.appr.state === 'void') return `The approval is void (${ctx.appr.reason}). A person re-approves it: node scripts/guard/approve-plan.mjs ${plan}`;
  if (ctx.scope && !ctx.scope.ok) return `${ctx.scope.outside.length} changed file(s) are outside the plan. Revert them, or amend ${plan} and ask for re-approval.`;
  const failing = Object.entries(ctx.status.gates ?? {}).find(([, g]) => g.result === 'fail');
  if (failing) return `Gate "${failing[0]}" failed at ${failing[1].ran_at}; its summary is under "Last failure".`;
  if (ctx.scenarios.applicable && !ctx.scenarios.ok) return `Tests are missing for: ${ctx.scenarios.missing.join(', ')}. Write them first and watch them fail.`;
  if (!ctx.status.updated_at) return `No gate run is recorded yet: node scripts/guard/run.mjs ${module}`;
  if (ctx.stale) return `Files changed since the last gate run (${ctx.status.updated_at}): node scripts/guard/run.mjs ${module}`;
  if (!ctx.status.final) return `All gates pass on a cached run. Before reporting done: node scripts/guard/run.mjs ${module} --final, and paste its output into the PR.`;
  return 'All gates pass on a --final run against the current files.';
}

export function buildHandoff(root, module) {
  const { plan } = readPlan(root, module);
  const planErrors = safe(() => checkPlan(root, module).errors, (e) => [e.message]);
  const appr = approval(root, module);
  const scope = appr.state === 'valid' ? safe(() => checkScope(root, module), () => null) : null;
  const scenarios = safe(() => checkScenarios(root, module), () => ({ applicable: false, required: [], covered: [], missing: [], ok: true }));
  const status = readStatus(root, module);
  const stale = Boolean(status.tree_hash) && status.tree_hash !== treeHash(root);
  const branch = safe(() => git(root, ['branch', '--show-current']).trim(), () => '?');
  const head = safe(() => git(root, ['rev-parse', '--short', 'HEAD']).trim(), () => '?');

  const out = [];
  out.push(`# Guard handoff: ${module}`, '');
  out.push(`Generated by scripts/guard/report.mjs at ${new Date().toISOString()} from git and the gate ledger.`, '');
  out.push('## Plan');
  out.push(`- Plan file: ${planPath(module)} (kind: ${plan.kind}). Branch ${branch}, HEAD ${head}.`);
  out.push(`- Approval: ${appr.state === 'valid' ? `valid, approved ${appr.stamp.approved_at} at base ${appr.stamp.base.slice(0, 7)}` : appr.state === 'missing' ? 'missing' : `void (${appr.reason})`}.`);
  if (planErrors.length) out.push(...cap(planErrors, 5).map((e) => `- Plan error: ${e}`));
  out.push('');

  out.push('## Gates');
  if (!status.updated_at) out.push('- No gate run recorded.');
  else {
    out.push(`- Last run ${status.updated_at}${status.final ? ' (--final)' : ''}; files ${stale ? 'changed since then' : 'unchanged since then'}.`);
    for (const [name, g] of Object.entries(status.gates)) out.push(`- ${g.result.toUpperCase()}: ${name}${g.cached ? ' (cached)' : ''}`);
  }
  out.push('');

  out.push('## Scope');
  if (scope) {
    out.push(`- ${scope.inside.length} changed file(s) in plan, ${scope.outside.length} outside, ${scope.exempt.length} exempt.`);
    out.push(...cap(scope.outside, 10).map((f) => `- Outside plan: ${f}`));
  } else out.push('- Not checked: the plan is not approved.');
  out.push('');

  out.push('## Scenario coverage');
  if (!scenarios.applicable) out.push('- Not applicable: the plan lists no scenario IDs.');
  else {
    out.push(`- Covered (${scenarios.covered.length}/${scenarios.required.length}): ${scenarios.covered.join(', ') || 'none'}`);
    out.push(`- Missing: ${scenarios.missing.join(', ') || 'none'}`);
  }
  out.push('');

  const failing = Object.entries(status.gates ?? {}).filter(([, g]) => g.result === 'fail');
  if (failing.length) {
    out.push('## Last failure');
    for (const [name, g] of failing.slice(0, 2)) {
      out.push(`- ${name} (${g.ran_at}):`, '```', ...g.summary.slice(-12), '```');
    }
    out.push('');
  }

  out.push('## Next step', `- ${nextStep(module, { planErrors, appr, scope, status, scenarios, stale })}`, '');

  const notes = readJsonl(root, 'notes', module).slice(-10);
  if (notes.length) {
    out.push('## Agent notes (claims, not verified)');
    out.push(...notes.map((n) => `- ${n.at}: ${n.text}`), '');
  }

  let text = out.join('\n');
  if (text.length > HANDOFF_MAX_CHARS) text = `${text.slice(0, HANDOFF_MAX_CHARS - 80)}\n\n[truncated at ${HANDOFF_MAX_CHARS} characters]\n`;
  return text;
}

export function writeHandoff(root, module) {
  const text = buildHandoff(root, module);
  writeLedgerFile(root, `handoff/${module}.md`, text);
  return text;
}

async function main() {
  const args = process.argv.slice(2);
  const root = repoRoot();
  const module = args.find((a) => !a.startsWith('--')) ?? activeModule(root);
  if (!module) throw new GuardError('no module given and no active plan (.guard/active)');
  const text = writeHandoff(root, module);
  console.log(args.includes('--print') ? text : `wrote .guard/handoff/${module}.md (${text.length} chars)`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) cli(main);
